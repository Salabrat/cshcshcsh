async def add_products_to_countries():
    conn = await aiosqlite.connect('database.db')
    
    # Get the parent ID for "Приватный IPv4"
    cursor = await conn.execute("SELECT id FROM catalog_items WHERE name = '👤Приватный IPv4'")
    private_ipv4 = await cursor.fetchone()
    
    if not private_ipv4:
        print("Private IPv4 category not found")
        await conn.close()
        return
    
    parent_id = private_ipv4[0]
    print(f"Private IPv4 category ID: {parent_id}")
    
    # Get all countries
    cursor = await conn.execute("""
        SELECT id, name FROM catalog_items 
        WHERE parent_id = ? AND type = 'subcategory'
        ORDER BY name
    """, (parent_id,))
    
    countries = await cursor.fetchall()
    
    print(f"Found {len(countries)} countries. Adding products...")
    
    total_products_added = 0
    
    for country_id, country_name in countries:
        # Extract country name without flag emoji
        clean_country_name = country_name[2:] if country_name.startswith('🇦') else country_name
        
        # Get regions for this country or use default
        regions = country_regions.get(clean_country_name, ["Центральный регион", "Северный регион", "Южный регион", "Восточный регион", "Западный регион"])
        
        # Get subnet range for this country
        subnet_base = subnet_ranges.get(clean_country_name, subnet_ranges["default"])
        
        print(f"\nProcessing {clean_country_name} (ID: {country_id}) - Adding {len(regions)} regions...")
        
        for i, region in enumerate(regions):
            try:
                # Create product name
                product_name = region
                
                # Create subnet range (generate random last two octets)
                subnet = f"{subnet_base}.{random.randint(0, 255)}.{random.randint(0, 255)}"
                
                # Generate random price between 300 and 700 rubles (in kopecks)
                price_kopecks = random.randint(30000, 70000)
                
                # Create product description
                description = f"""🌐 Прокси-сервер

Тип: Приватный IPv4

Список подсетей: {subnet}.*.* - генерируй в зависимости от страны/региона

Страна: {clean_country_name}

Регион: {region}"""
                
                # Add product to database
                cursor = await conn.execute('''
                    INSERT INTO catalog_items 
                    (parent_id, type, name, description, sticker_id, photo_id, preview_link, 
                     row_width, position, is_grid_3x6)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ''', (
                    country_id,  # parent_id (country)
                    'product',   # type
                    product_name,  # name
                    description,  # description
                    None,  # sticker_id
                    None,  # photo_id
                    None,  # preview_link
                    1,  # row_width
                    i,  # position
                    0   # is_grid_3x6 (products don't use grid)
                ))
                
                product_id = cursor.lastrowid
                await conn.commit()
                
                # Add product price with expiration days
                expiration_days = "30,60,90,120,150,180"
                await conn.execute('''
                    INSERT OR REPLACE INTO product_prices 
                    (product_id, price, currency, expiration_days)
                    VALUES (?, ?, ?, ?)
                ''', (product_id, price_kopecks, 'RUB', expiration_days))
                await conn.commit()
                
                # Generate proxy files for this product
                files_added = 0
                for day_period in [30, 60, 90, 120, 150, 180]:
                    # Generate 5 proxy addresses per day period
                    for j in range(5):
                        # Generate a fake proxy address
                        proxy_ip = f"{subnet}.{random.randint(0, 255)}.{random.randint(0, 255)}"
                        proxy_port = random.randint(1000, 65535)
                        proxy_username = f"user{random.randint(1000, 9999)}"
                        proxy_password = f"pass{random.randint(10000, 99999)}"
                        
                        # Create proxy file content
                        proxy_content = f"{proxy_ip}:{proxy_port}:{proxy_username}:{proxy_password}"
                        file_name = f"proxy_{region}_{day_period}days_{j+1}.txt"
                        
                        # Add file to product
                        await conn.execute('''
                            INSERT INTO product_files 
                            (product_id, file_id, file_type, file_name, position, day_period)
                            VALUES (?, ?, ?, ?, ?, ?)
                        ''', (product_id, proxy_content, 'document', file_name, j, day_period))
                        await conn.commit()
                        files_added += 1
                
                print(f"  ✓ Added product '{product_name}' (ID: {product_id}) with {files_added} proxy files")
                total_products_added += 1
                
            except Exception as e:
                print(f"  ✗ Error adding product for region '{region}': {e}")
    
    print(f"\nFinished! Total products added: {total_products_added}")
    await conn.close()

